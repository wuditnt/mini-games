/** 某一波的敌人列表（不含终波 Boss / 精英） */
export function waveEnemies(def: LevelDef, wave: number): EnemyKind[] {
  const plan = def.waves[wave - 1];
  if (!plan) return [];
  const list: EnemyKind[] = [];
  for (let i = 0; i < plan[0]; i++) list.push('scout');
  for (let i = 0; i < plan[1]; i++) list.push('grunt');
  for (let i = 0; i < plan[2]; i++) list.push('heavy');
  return list;
}

/** 一关的敌人总数（含 Boss 与精英） */
export function levelEnemyTotal(def: LevelDef): number {
  const base = def.waves.reduce((n, p) => n + p[0] + p[1] + p[2], 0);
  return base + 1 + (def.elite ? 1 : 0);
}
